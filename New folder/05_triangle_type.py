# پاسخ سؤال ۵ — بررسی نوع مثلث

a = float(input("طول ضلع اول را وارد کنید: "))
b = float(input("طول ضلع دوم را وارد کنید: "))
c = float(input("طول ضلع سوم را وارد کنید: "))

# بررسی مثبت بودن طول ضلع‌ها
if a <= 0 or b <= 0 or c <= 0:
    print("طول ضلع‌ها نامعتبر است.")

# بررسی امکان تشکیل مثلث
elif a + b <= c or a + c <= b or b + c <= a:
    print("با این سه ضلع نمی‌توان مثلث تشکیل داد.")

else:
    # بررسی متساوی‌الاضلاع بودن
    if a == b and b == c:
        print("مثلث متساوی‌الاضلاع است.")

    # بررسی متساوی‌الساقین بودن
    if a == b or a == c or b == c:
        print("مثلث متساوی‌الساقین است.")

    # بررسی قائم‌الزاویه بودن در هر سه حالت ممکن
    if (a ** 2 + b ** 2 == c ** 2) or (a ** 2 + c ** 2 == b ** 2) or (b ** 2 + c ** 2 == a ** 2):
        print("مثلث قائم‌الزاویه است.")

    # بررسی معمولی بودن
    if a != b and a != c and b != c and        (a ** 2 + b ** 2 != c ** 2) and        (a ** 2 + c ** 2 != b ** 2) and        (b ** 2 + c ** 2 != a ** 2):
        print("مثلث معمولی است.")
