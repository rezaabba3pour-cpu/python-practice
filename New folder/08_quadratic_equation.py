# پاسخ سؤال ۸ — تحلیل معادله درجه دو و حالت‌های ویژه

a = float(input("ضریب a را وارد کنید: "))
b = float(input("ضریب b را وارد کنید: "))
c = float(input("ضریب c را وارد کنید: "))

# اگر a صفر باشد، معادله درجه دو نیست
if a == 0:

    # حالت معادله درجه یک
    if b != 0:
        root = -c / b
        print("معادله درجه یک است.")
        print("ریشه:", root)

    # اگر همه ضرایب صفر باشند
    elif c == 0:
        print("معادله بی‌نهایت جواب دارد.")

    # اگر a و b صفر و c ناصفر باشد
    else:
        print("معادله جواب ندارد.")

else:
    # محاسبه دلتا
    delta = (b ** 2) - (4 * a * c)

    # دو ریشه حقیقی
    if delta > 0:
        root1 = (-b + delta ** 0.5) / (2 * a)
        root2 = (-b - delta ** 0.5) / (2 * a)

        print("معادله دو ریشه حقیقی دارد.")
        print("ریشه اول:", root1)
        print("ریشه دوم:", root2)

    # یک ریشه حقیقی
    elif delta == 0:
        root = -b / (2 * a)

        print("معادله یک ریشه حقیقی دارد.")
        print("ریشه:", root)

    # بدون ریشه حقیقی
    else:
        print("ریشه حقیقی ندارد.")
