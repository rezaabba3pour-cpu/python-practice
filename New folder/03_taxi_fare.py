# پاسخ سؤال ۳ — محاسبه کرایه تاکسی اینترنتی

distance = float(input("مسافت سفر را بر حسب کیلومتر وارد کنید: "))
start_hour = int(input("ساعت شروع سفر را از ۰ تا ۲۳ وارد کنید: "))
weather = input("وضعیت آب‌وهوا را وارد کنید (عادی/بارانی): ")

# بررسی معتبر بودن مسافت
if distance < 0:
    print("مسافت واردشده نامعتبر است.")

# بررسی معتبر بودن ساعت
elif start_hour < 0 or start_hour > 23:
    print("ساعت واردشده نامعتبر است.")

# بررسی معتبر بودن وضعیت آب‌وهوا
elif weather != "عادی" and weather != "بارانی":
    print("وضعیت آب‌وهوا نامعتبر است.")

else:
    # محاسبه کرایه اولیه
    fare = 50000 + (distance * 12000)

    # افزایش کرایه در ساعت‌های پرترافیک
    if (7 <= start_hour <= 9) or (17 <= start_hour <= 20):
        fare = fare + (fare * 20 / 100)

    # افزایش کرایه در هوای بارانی
    if weather == "بارانی":
        fare = fare + (fare * 15 / 100)

    # تخفیف برای مسافت بیشتر از ۲۰ کیلومتر
    if distance > 20:
        fare = fare - (fare * 10 / 100)

    print("کرایه نهایی:", fare)
